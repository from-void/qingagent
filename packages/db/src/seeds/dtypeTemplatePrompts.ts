export function withDtypeCommonConstraints(dtype: string, prompt: string): string {
  const constraints = DTYPE_COMMON_CONSTRAINTS[dtype as DerivativeTemplateDtype];
  return constraints ? `${constraints}\n\n${prompt}` : prompt;
}
